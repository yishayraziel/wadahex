"""Turn all.json (per-sample fits) into Source/SDS5Library.h: balanced, pitch-ordered kits."""
import json, re, numpy as np, os, sys
sys.argv = [sys.argv[0]]
os.environ.setdefault("EXTRA_PARAMS", '[["toneLP",150,20000,1,18,20000],["noiseHP",20,3000,1,19,20]]')
from fit import render, N

fits = {r["file"]: r for r in json.load(open("all.json"))}

def peak_of(r):
    y = render(np.array(list(r["params"].values()), np.float32), 0)
    return float(np.max(np.abs(y[: int(0.3 * 44100)]))) + 1e-6

def voice(file, target_db, pan=0.0):
    r = fits[file]; p = r["params"]
    level = 10 ** (target_db / 20) / peak_of(r) * 0.6       # drive stage is ~unity, leave headroom
    level_db = float(np.clip(20 * np.log10(level), -40, 6))
    def f(v):
        t = f"{v:.4g}"
        return (t if ("." in t or "e" in t) else t + ".0") + "f"
    return ("[] { PadParams q = sdsBase(); "
            f"q.tonePitch = {f(p['tonePitch'])}; q.bend = {f(p['bend'])}; q.bendTime = {f(p['bendTime'])}; q.toneDecay = {f(p['toneDecay'])}; "
            f"q.toneLvl = {f(p['toneLvl'])}; q.shape = {f(p['shape'])}; q.noiseLvl = {f(p['noiseLvl'])}; q.noiseDecay = {f(p['noiseDecay'])}; "
            f"q.noiseColor = {f(p['noiseColor'])}; q.noiseSweep = {f(p['noiseSweep'])}; q.cutoff = {f(p['cutoff'])}; q.reso = {f(p['reso'])}; "
            f"q.filtEnv = {f(p['filtEnv'])}; q.filtDecay = {f(p['filtDecay'])}; q.click = {f(p['click'])}; q.drive = {f(p['drive'])}; "
            f"q.toneLP = {f(p['toneLP'])}; q.noiseHP = {f(p['noiseHP'])}; q.level = {f(10 ** (level_db / 20))}; q.pan = {f(pan)}; "
            f"return q; }}() /* {file}, fit loss {r['loss']} */")

num = lambda s: int(re.findall(r"\d+", s)[0]) if re.findall(r"\d+", s) else 0
kicks  = sorted([k for k in fits if k.startswith("BDRUM")], key=num)
snares = sorted([k for k in fits if k.startswith("SNARE")], key=num)
toms   = sorted([k for k in fits if k.startswith("TOM")], key=lambda k: -fits[k]["params"]["tonePitch"])
rims   = sorted([k for k in fits if k.startswith("RIMSHOT")], key=num)
quart  = [toms[i::4] for i in range(4)]                 # interleave so each kit gets high..low toms
quart  = [sorted(toms, key=lambda k: -fits[k]["params"]["tonePitch"])[i * len(toms) // 4:(i + 1) * len(toms) // 4] for i in range(4)]

TOM_PAN = [0.35, 0.12, -0.12, -0.35]
def kit(name, kick, snare, tomset, rim):
    tomset = sorted(tomset, key=lambda k: -fits[k]["params"]["tonePitch"])
    pads = [voice(kick, 0.0), voice(snare, -1.5)] + [voice(t, -3.0, TOM_PAN[i]) for i, t in enumerate(tomset)] + ["sdsClap()", voice(rim, -6.0, 0.2)]
    return f'        {{ "{name}", [] {{ return Kit {{ {", ".join(pads)} }}; }} }},'

kits = []
factory = "Simmons_sds5_kits/"
# the folder of a real SDS5 kit: kick, snare mid, toms 1-4
sds = kit("SDS-V", "SDS5 kick 2.wav", "SDS5 snare mid.wav", ["SDS5 tom 1.wav", "SDS5 tom 2.wav", "SDS5 tom 3.wav", "SDS5 tom 4.wav"], rims[0])
kits.append(sds)
for i in range(6):
    kits.append(kit(f"SDS5 Library {i + 1}", kicks[(i * 2) % len(kicks)], snares[(i * 3 + 1) % len(snares)],
                    [quart[q][i % len(quart[q])] for q in range(4)], rims[i % len(rims)]))

hdr = """#pragma once
// Generated by fit/make_kits.py from per-sample fits of real SDS5 one-shots.
// Every pad is pure synthesis: the parameters were found by matching the plugin's own
// voice to each recording (multi-resolution spectral distance). Do not edit by hand.
// Included from Presets.h (which defines Kit).

inline PadParams sdsBase()
{
    PadParams q; q.chip = 7; q.analogBend = true; q.toneFilt = false; q.velSens = 0.7f; q.velDecay = 0.35f;
    q.lfoRate = 6; q.lfoPitch = 0; q.lfoCut = 0; q.chipLvl = 0.5f;
    return q;
}

inline PadParams sdsClap()   // the SDS-V had no clap: noise bursts + the clap chip
{
    PadParams q; q.chip = 3; q.chipLvl = 0.7f; q.toneLvl = 0; q.noiseLvl = 0.55f; q.noiseDecay = 200; q.noiseColor = 0.75f;
    q.noiseHP = 600; q.click = 0.2f; q.cutoff = 8000; q.reso = 0.25f; q.filtEnv = 0.1f; q.level = 0.65f; q.pan = -0.15f;
    q.velSens = 0.7f;
    return q;
}

struct LibKit { const char* name; std::function<Kit()> make; };

inline const std::vector<LibKit>& sds5Kits()
{
    static const std::vector<LibKit> k = {
""" + "\n".join(kits) + """
    };
    return k;
}
"""
open("/home/claude/hex1/Source/SDS5Library.h", "w").write(hdr)
